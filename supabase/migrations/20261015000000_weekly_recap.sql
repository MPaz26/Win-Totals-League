-- Weekly recap emails: per-user opt-out, a token for signed-out unsubscribe links, and a
-- log of what's been sent so a re-run doesn't email anyone twice.
--
-- Kept out of profiles because every signed-in user can read every profile, and the
-- token is what authorizes an unsubscribe. No row means the defaults: subscribed, no
-- token yet. The weekly job (service role) creates rows for its recipients before sending.

create table public.email_preferences (
  user_id           uuid primary key references public.profiles (id) on delete cascade,
  weekly_recap      boolean not null default true,
  unsubscribe_token uuid not null unique default gen_random_uuid(),
  updated_at        timestamptz not null default now()
);

alter table public.email_preferences enable row level security;

create policy "own email prefs read" on public.email_preferences for select to authenticated
  using (user_id = auth.uid());
create policy "own email prefs insert" on public.email_preferences for insert to authenticated
  with check (user_id = auth.uid());
create policy "own email prefs update" on public.email_preferences for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- The token is generated by the database; users don't get to choose or change it.
-- user_id is updatable only because PostgREST upserts write it back; the policy pins it to the caller.
revoke insert, update on public.email_preferences from anon, authenticated;
grant insert (user_id, weekly_recap, updated_at), update (user_id, weekly_recap, updated_at)
  on public.email_preferences to authenticated;

-- Unsubscribe link from an email. Works signed out; returns false for an unknown token.
create function public.unsubscribe_weekly_recap(p_token uuid)
returns boolean
language sql
security definer
set search_path = ''
as $$
  with updated as (
    update public.email_preferences
       set weekly_recap = false, updated_at = now()
     where unsubscribe_token = p_token
    returning 1
  )
  select exists (select 1 from updated);
$$;

revoke execute on function public.unsubscribe_weekly_recap(uuid) from public;
grant execute on function public.unsubscribe_weekly_recap(uuid) to anon, authenticated;

-- One row per email sent ('recap/<date>/<league>/<user>'). Only the weekly job (service role) touches it.
create table public.recap_sends (
  key     text primary key,
  sent_at timestamptz not null default now()
);
alter table public.recap_sends enable row level security;
revoke all on public.recap_sends from anon, authenticated;
